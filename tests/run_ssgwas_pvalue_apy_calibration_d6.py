#!/usr/bin/env python3
"""Phase D gate D6: null calibration of R0 (Exact_Ginv) / R1 (APY-exact) /
R3 (APY-approx) ssGWAS SNP P-values under a STRICTLY model-consistent null.

Model-consistent null (the ssGBLUP precision model that the binary actually
solves, identity convention tau=omega=1, blend-I alpha=0.05):

    Gw       = (1-alpha)*G_raw + alpha*I
    Hinv     = Ainv + [0 0; 0 tau*Gw^-1 - omega*A22^-1]   (typed block)
    a ~ N(0, VA * H),  H = Hinv^-1   (drawn via Cholesky + triangular solve)
    y = 1 + a + e,     e ~ N(0, VE),  VA=1, VE=3  (exactly the --reml-vg/ve
                                                    fixed parameters of D5)

This is the inverse-precision draw used by gate C6 (run_ssgwas_pvalue_null_
calibration.py). Any block-replacement null (a ~ N(0, A + block(Gw - A22)))
puts the data outside the fitted family and inflates every SNP test, so it is
explicitly NOT used (ruling: no block replacement covariance).

For each regime x tier (data generated by the D5 harness, generators
unchanged) with R phenotype replicates (y resampled, genotypes/pedigree
fixed):

  R0  exact      (no core)
  R1  apy-exact  core in {K98, 0.5*K98, full}
  R3  apy-approx core in {K98, 0.5*K98, full}

Metrics per cell (no genomic control, no rescale, no P recalibration):

  lambda_GC (median chi2_1df / 0.4549364), QQ max decile deviation,
  FPR@0.05/0.01/0.001, median_Z, Var(Z), P uniformity KS statistic.
  Pairwise error attribution R0-R1 (L1), R1-R3 (L2), R0-R3 (TOT).

Verdicts (per cell and overall): PASS / CONCERN / FAIL.
FAIL is reserved for clear type-I error inflation (FPR@0.05 beyond 3*MC-SE
AND lambda beyond 3*SE, LD-robustness scaled). Approximation bias alone is
CONCERN, never FAIL. A computed non-finite / solver failure is reported
separately as NUMERICAL and counted as FAIL.

Q1-Q6 answers are assembled in the summary JSON.

Usage:
  python3 tests/run_ssgwas_pvalue_apy_calibration_d6.py \
      --bin build/cosmicscanner \
      --outdir tests/results/ssgwas_pvalue_apy_d6 \
      --tiers 0          # pilot; omit for all
  python3 tests/run_ssgwas_pvalue_apy_calibration_d6.py \
      --regime livestock \
      --outdir tests/results/ssgwas_pvalue_apy_d6_livestock
"""
import argparse
import json
import math
import os
import sys

import numpy as np

from run_ssgwas_pvalue_apy_medium_benchmark import (
    ALPHA, TIERS, VA, VE,
    build_g, build_pedigree, build_pedigree_livestocklike, k98_of,
    load_meta, load_pvalue, relationship_matrix, run_cs,
    simulate_dosages, simulate_dosages_livestock, write_plink_trio)

from math import erfc as math_erfc

erfc = np.vectorize(math_erfc)
CHI2_MEDIAN_1DF = 0.45493642311957277


def build_cores(k98, n_g):
    """Fixed D6 core set per regime: {K98, 0.5*K98, full}. Dedup, no other
    cores allowed (no adaptive policy in D6)."""
    cores = []
    for c in (int(round(0.5 * k98)), k98, n_g):
        c = min(max(c, 1), n_g)
        if c not in cores:
            cores.append(c)
    return cores


def null_precision(ped, typed_idx_ped, dos, alpha=ALPHA):
    """Strict model-consistent null: returns (A, L) with
    Hinv = Ainv + block(tau*Gw^-1 - omega*A22^-1), tau=omega=1, and
    L = Cholesky(Hinv) so a = L^-T z ~ N(0, H), H = Hinv^-1."""
    A, _ = relationship_matrix(ped)
    n = len(ped)
    o = np.ix_(typed_idx_ped, typed_idx_ped)
    G, S, pj = build_g(dos)
    Gw = (1.0 - alpha) * G + alpha * np.eye(G.shape[0])
    A22 = A[o]
    Hinv = np.linalg.inv(A).copy()
    Hinv[o] += np.linalg.inv(Gw) - np.linalg.inv(A22)
    Hinv = 0.5 * (Hinv + Hinv.T)
    L = np.linalg.cholesky(Hinv)
    return A, L


def draw_null_a(L, rng):
    """a ~ N(0, H) with H = (LL')^-1: a = L^-T z."""
    z = rng.normal(size=L.shape[0])
    try:
        from scipy.linalg import solve_triangular
        return solve_triangular(L.T, z, lower=False)
    except ImportError:
        return np.linalg.solve(L.T, z)


def calibration_metrics(z):
    """Per-run null-calibration metrics on a finite Z vector."""
    p = erfc(np.abs(z) / np.sqrt(2.0))
    chi2 = z ** 2
    lam = float(np.median(chi2) / CHI2_MEDIAN_1DF)
    n = len(z)
    bins = np.histogram(p, bins=np.linspace(0, 1, 11))[0]
    qq_dev = float(np.max(np.abs(bins / n - 0.1)))
    p_s = np.sort(p)
    ks = float(np.max(np.maximum(
        (np.arange(1, n + 1) / n) - p_s, p_s - (np.arange(n)) / n)))
    out = {"lambda_GC": lam, "FPR@0.05": float(np.mean(p < 0.05)),
           "FPR@0.01": float(np.mean(p < 0.01)),
           "FPR@0.001": float(np.mean(p < 0.001)),
           "median_Z": float(np.median(z)), "Var_Z": float(np.var(z)),
           "QQ_dev": qq_dev, "KS_D": ks, "n_finite": n}
    return out


def pooled_verdict(st):
    """PASS / CONCERN / FAIL on pooled statistics with LD-robust SEs.
    FAIL = clear type-I inflation: FPR@0.05 > 0.05 + 3*MC-SE AND
    lambda > 1 + 3*SE_lambda."""
    lam = st["lambda_pooled"]
    se_lam = st["lambda_se"]
    f05 = st["fpr05"]
    se_f05 = st["fpr05_se"]
    if (f05 - 0.05 > 3.0 * se_f05) and (lam > 1.0 + 3.0 * se_lam):
        return "FAIL", "clear type-I inflation (FPR@0.05 and lambda)"
    reasons = []
    if abs(lam - 1.0) > 3.0 * se_lam:
        reasons.append("lambda_GC outside 3*SE")
    if abs(f05 - 0.05) > 3.0 * se_f05:
        reasons.append("FPR@0.05 outside 3*MC-SE")
    if st["QQ_dev"] > st["QQ_bound"]:
        reasons.append("QQ dev above bound")
    if st["KS_D"] > 1.36 / math.sqrt(st["n_tests"]):
        reasons.append("KS above 95% bound")
    if reasons:
        return "CONCERN", ";".join(reasons)
    return "PASS", ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--seed", type=int, default=123)
    ap.add_argument("--tiers", default="all",
                    help="comma list e.g. 0,1 (indices into TIERS)")
    ap.add_argument("--regime", default="stress",
                    choices=["stress", "livestock"])
    ap.add_argument("--reps", default="5,3,1",
                    help="replicates per tier index 0,1,2 (y resampled)")
    ap.add_argument("--omp", type=int, default=8)
    args = ap.parse_args()

    reps = [int(x) for x in args.reps.split(",")]
    assert len(reps) == 3
    rng = np.random.default_rng(args.seed)
    os.makedirs(args.outdir, exist_ok=True)
    work = f"{args.outdir}/data"
    os.makedirs(work, exist_ok=True)

    tiers = list(range(len(TIERS)))
    if args.tiers != "all":
        tiers = [int(t) for t in args.tiers.split(",")]

    regime = ("HIGH_DIMENSIONAL_STRESS" if args.regime == "stress"
              else "LIVESTOCK_LIKE_LD")
    summary = {"regime": regime, "reps_per_tier": reps, "cells": {},
               "pairs": {}, "q": {}, "tiers": []}
    pairwise_rows = []

    for ti in tiers:
        n_g, m, n_chr = TIERS[ti]
        n_ped = 3 * n_g // 2
        n_rep = reps[ti]
        tag = f"t{ti}_ng{n_g}"
        tier_out = f"{args.outdir}/{tag}"
        os.makedirs(tier_out, exist_ok=True)

        # ---- data generation identical to D5 (generators unchanged) ----
        rng_t = np.random.default_rng(args.seed * 7919 + ti * 104729)
        if args.regime == "livestock":
            ped, typed_ids, geno_info = build_pedigree_livestocklike(
                n_ped, n_g, m, rng_t)
            idx = {r[0]: i for i, r in enumerate(ped)}
            typed_idx_ped = np.array([idx[i] for i in typed_ids])
            dos, per_ch = simulate_dosages_livestock(
                ped, idx, typed_idx_ped, m, rng_t, geno_info)
        else:
            ped, typed_ids, n0, n1, n2 = build_pedigree(n_ped, rng_t)
            idx = {r[0]: i for i, r in enumerate(ped)}
            typed_idx_ped = np.array([idx[i] for i in typed_ids])
            dos = simulate_dosages(ped, idx, typed_idx_ped, m, n_chr, rng_t)
        G_raw, S_2pq, pj = build_g(dos)
        G_bs = (1.0 - ALPHA) * G_raw + ALPHA * np.eye(n_g)
        k98 = k98_of(G_bs)
        cores = build_cores(k98, n_g)
        assert cores[-1] == n_g, cores
        half = int(round(0.5 * k98))

        A, L = null_precision(ped, typed_idx_ped, dos)

        # ---- static analysis files (genotypes/pedigree fixed) ----
        write_plink_trio(f"{work}/sim", typed_ids, dos, rng_t)
        with open(f"{work}/sim.cs.ped", "w") as f:
            for r in ped:
                f.write(f"{r[0]} {r[1]} {r[2]}\n")

        n_rec = int(0.7 * n_ped)
        pids = sorted(set(rng_t.choice(list(range(1, n_ped + 1)),
                                       size=n_rec, replace=False)))
        p_rows = np.array([idx[i] for i in pids])

        tier_sum = {"tier": tag, "n_g": n_g, "M": m, "n_ped": n_ped,
                    "K98": k98, "K98_N_G": round(k98 / n_g, 4),
                    "cores": cores, "replicates": n_rep}
        summary["tiers"].append(tier_sum)
        print(f"[tier {ti}] regime={regime} n_g={n_g} M={m} K98={k98} "
              f"(K98/N={k98 / n_g:.3f}) cores={cores} reps={n_rep}")

        # per-cell accumulators (pooled over reps)
        acc = {"R0_exact": {"z2": [], "p": [], "z": [], "lam_rep": []}}
        for c in cores:
            acc[f"R1_apy-exact_core{c}"] = {"z2": [], "p": [], "z": [],
                                            "lam_rep": []}
            acc[f"R3_apy-approx_core{c}"] = {"z2": [], "p": [], "z": [],
                                             "lam_rep": []}

        run_specs = [("R0_exact", "exact", None, None)]
        for c in cores:
            ratio = (0.5 if c == half else 1.0 if c == k98
                     else round(n_g / k98, 4))
            run_specs.append((f"R1_apy-exact_core{c}", "apy-exact", c, ratio))
            run_specs.append((f"R3_apy-approx_core{c}", "apy-approx", c,
                              ratio))

        for rep in range(1, n_rep + 1):
            rng_y = np.random.default_rng(args.seed * 104729 + ti * 101 + rep)
            a = draw_null_a(L, rng_y)
            y = 1.0 + a[p_rows] + rng_y.normal(scale=math.sqrt(VE),
                                               size=len(p_rows))
            with open(f"{work}/sim_y.phe", "w") as f:
                f.write("FID IID Pheno_1\n")
                for k, r in enumerate(p_rows):
                    f.write(f"F{ped[r][0]} {ped[r][0]} {y[k]:.10f}\n")
            rep_out = f"{tier_out}/rep{rep:02d}"
            for key, meth, c, ratio in run_specs:
                if meth == "exact":
                    d = f"{rep_out}/exact"
                else:
                    d = f"{rep_out}/{key}"
                pv_path = f"{d}/m2.ss_backsolve.pvalue.txt"
                if not os.path.exists(pv_path):
                    run_cs(args.bin, work, d, meth, core=c,
                           ratio=(ratio if c else None), omp=args.omp)
                pv = load_pvalue(pv_path)
                meta = load_meta(f"{d}/m2.ss_backsolve.meta.txt")
                if meth == "exact":
                    assert meta.get("DENSE_NG2_ALLOCATED") == "true"
                else:
                    assert meta.get("DENSE_NG2_ALLOCATED") == "false"
                    assert abs(int(meta.get("K98_G", -1)) - k98) <= 2
                    if meth == "apy-approx":
                        assert meta.get("GENOMIC_CONTROL_APPLIED", "?") \
                            == "false"
                z = pv[3]
                cell = acc[key]
                if len(z):
                    m0 = calibration_metrics(z)
                    cell["z2"].append(z ** 2)
                    cell["p"].append(erfc(np.abs(z) / np.sqrt(2.0)))
                    cell["z"].append(z)
                    cell["lam_rep"].append(m0["lambda_GC"])
            print(f"  rep {rep:02d}: [{', '.join(s[0] for s in run_specs)}] "
                  "finished")

        # ---- pooled calibration stats per cell ----
        def agg(cell):
            if not cell["z"]:
                return None
            n = sum(len(z) for z in cell["z"])
            z = np.concatenate(cell["z"])
            z2 = np.concatenate(cell["z2"])
            p = np.concatenate(cell["p"])
            lam_pooled = float(np.median(z2) / CHI2_MEDIAN_1DF)
            lam_rep = np.array(cell["lam_rep"])
            emp_sd = float(lam_rep.std(ddof=1)) if len(lam_rep) > 1 else 0.0
            f_ld = max(1.0, emp_sd / math.sqrt(2.0 / len(lam_rep)))
            se_lam = math.sqrt(2.0 / max(n, 1)) * f_ld
            fpr05 = float(np.mean(p < 0.05))
            se_f05 = math.sqrt(0.05 * 0.95 / n) * f_ld
            bins = np.histogram(p, bins=np.linspace(0, 1, 11))[0]
            qq_dev = float(np.max(np.abs(bins / n - 0.1)))
            ps = np.sort(p)
            ks = float(np.max(np.maximum(
                (np.arange(1, n + 1) / n) - ps,
                ps - (np.arange(n)) / n)))
            qq_bound = 3.0 * math.sqrt(0.1 * 0.9 / n) * f_ld
            st = {"n_tests": n, "lambda_pooled": lam_pooled,
                  "lambda_mean_rep": float(lam_rep.mean()),
                  "lambda_se": se_lam, "f_ld": f_ld,
                  "fpr05": fpr05, "fpr05_se": se_f05,
                  "fpr01": float(np.mean(p < 0.01)),
                  "fpr001": float(np.mean(p < 0.001)),
                  "median_Z": float(np.median(z)),
                  "Var_Z": float(np.var(z)),
                  "QQ_dev": qq_dev, "QQ_bound": qq_bound, "KS_D": ks}
            verdict, why = pooled_verdict(st)
            st["verdict"] = verdict
            st["why"] = why
            return st

        for key, cell in acc.items():
            st = agg(cell)
            if st is None:
                st = {"n_tests": 0, "verdict": "FAIL",
                      "why": "no finite Z (numerical)"}
            summary["cells"][f"{tag}_{key}"] = st
            print(f"  {key:<24} lambda={st['lambda_pooled']:.4f} "
                  f"FPR05={st['fpr05']:.5f} FPR01={st['fpr01']:.5f} "
                  f"FPR001={st['fpr001']:.6f} medZ={st['median_Z']:+.4f} "
                  f"VarZ={st['Var_Z']:.4f} QQ={st['QQ_dev']:.4f}/"
                  f"{st['QQ_bound']:.4f} KS={st['KS_D']:.4f} "
                  f"-> {st['verdict']}")

        # ---- pairwise error attribution on Z (elementwise, per rep, then
        # pooled) ----
        for rep in range(1, n_rep + 1):
            rep_out = f"{tier_out}/rep{rep:02d}"
            rows = {}
            for key, meth, c, ratio in run_specs:
                d = f"{rep_out}/exact" if meth == "exact" else \
                    f"{rep_out}/{key}"
                pv = load_pvalue(f"{d}/m2.ss_backsolve.pvalue.txt")
                rows[key] = dict(zip(pv[0], pv[3]))
            for c in cores:
                k1 = f"R1_apy-exact_core{c}"
                k3 = f"R3_apy-approx_core{c}"
                for lbl, da, db in (("R0-R1", rows["R0_exact"], rows[k1]),
                                    ("R1-R3", rows[k1], rows[k3]),
                                    ("R0-R3", rows["R0_exact"], rows[k3])):
                    common = sorted(set(da) & set(db))
                    if len(common) < 2:
                        continue
                    za = np.array([da[s] for s in common])
                    zb = np.array([db[s] for s in common])
                    ok = np.isfinite(za) & np.isfinite(zb)
                    za, zb = za[ok], zb[ok]
                    if len(za) < 2:
                        continue
                    r = float(np.corrcoef(za, zb)[0, 1])
                    slope = float(np.cov(za, zb, ddof=0)[0, 1] /
                                  np.var(za))
                    rmse = float(np.sqrt(np.mean((za - zb) ** 2)))
                    mae = float(np.mean(np.abs(za - zb)))
                    pairwise_rows.append(
                        {"regime": regime, "tier": tag, "core": c,
                         "pair": lbl, "n_snp": int(len(za)),
                         "pearson": r, "slope": slope, "rmse": rmse,
                         "mean_abs_diff": mae})

        # ---- pair lambda attribution (pooled medians) ----
        for c in cores:
            lam0 = summary["cells"][f"{tag}_R0_exact"]["lambda_pooled"]
            lam1 = summary["cells"][f"{tag}_R1_apy-exact_core{c}"][
                "lambda_pooled"]
            lam3 = summary["cells"][f"{tag}_R3_apy-approx_core{c}"][
                "lambda_pooled"]
            d1 = abs(lam1 - lam0)
            d2 = abs(lam3 - lam1)
            dT = abs(lam3 - lam0)
            summary["pairs"][f"{tag}_core{c}"] = {
                "lambda_R0": lam0, "lambda_R1": lam1, "lambda_R3": lam3,
                "dlambda_L1_R0_R1": d1, "dlambda_L2_R1_R3": d2,
                "dlambda_TOT_R0_R3": dT,
                "lambda_share_L1": (d1 / dT if dT > 0 else float("nan")),
                "lambda_share_L2": (d2 / dT if dT > 0 else float("nan"))}

    # ---- Q1-Q6 ----
    def cell(tkey):
        return summary["cells"].get(tkey, {})

    q = {}
    q1 = {}
    for ti in tiers:
        tag = f"t{ti}_ng{TIERS[ti][0]}"
        k = summary["tiers"][ti]["K98"]
        for name, core_v in (("K98", k), ("full", TIERS[ti][0])):
            st = cell(f"{tag}_R3_apy-approx_core{core_v}")
            q1[f"t{ti}_{name}"] = {
                "core": core_v, "lambda_GC": st.get("lambda_pooled"),
                "lambda_se": st.get("lambda_se"),
                "FPR@0.05": st.get("fpr05"),
                "FPR@0.05_se": st.get("fpr05_se"),
                "QQ_dev": st.get("QQ_dev"), "KS_D": st.get("KS_D"),
                "verdict": st.get("verdict"), "why": st.get("why")}
    q["Q1"] = q1

    q2 = {}
    for ti in tiers:
        tag = f"t{ti}_ng{TIERS[ti][0]}"
        k = summary["tiers"][ti]["K98"]
        h = int(round(0.5 * k))
        st_k = cell(f"{tag}_R3_apy-approx_core{k}")
        st_h = cell(f"{tag}_R3_apy-approx_core{h}")
        q2[f"t{ti}"] = {"K98": k, "halfK98": h,
                        "K98_lambda": st_k.get("lambda_pooled"),
                        "halfK98_lambda": st_h.get("lambda_pooled"),
                        "delta_lambda_K98_minus_half":
                            float((st_k.get("lambda_pooled") or float("nan"))
                                  - (st_h.get("lambda_pooled")
                                     or float("nan"))),
                        "K98_verdict": st_k.get("verdict"),
                        "halfK98_verdict": st_h.get("verdict")}
    q["Q2"] = q2

    q3 = {}
    for ti in tiers:
        tag = f"t{ti}_ng{TIERS[ti][0]}"
        k = summary["tiers"][ti]["K98"]
        q3[f"t{ti}"] = {"K98_N_G": summary["tiers"][ti]["K98_N_G"],
                        "lambda_R3_K98": cell(
                            f"{tag}_R3_apy-approx_core{k}").get(
                                "lambda_pooled"),
                        "lambda_R0_exact": cell(
                            f"{tag}_R0_exact").get("lambda_pooled"),
                        "lambda_R3_full": cell(
                            f"{tag}_R3_apy-approx_core"
                            f"{TIERS[ti][0]}").get("lambda_pooled")}
    q["Q3"] = q3

    q4 = {}
    for ti in tiers:
        tag = f"t{ti}_ng{TIERS[ti][0]}"
        k = summary["tiers"][ti]["K98"]
        row = summary["pairs"].get(f"{tag}_core{k}", {})
        q4[f"t{ti}"] = {"lambda_R3": row.get("lambda_R3"),
                        "lambda_share_L1": row.get("lambda_share_L1"),
                        "lambda_share_L2": row.get("lambda_share_L2")}
    q["Q4"] = q4

    q5 = {}
    for ti in tiers:
        tag = f"t{ti}_ng{TIERS[ti][0]}"
        k = summary["tiers"][ti]["K98"]
        for name, c in (("K98", k), ("full", TIERS[ti][0])):
            row = summary["pairs"].get(f"{tag}_core{c}", {})
            q5.setdefault(f"t{ti}", {})[name] = {
                "lambda_share_L1": row.get("lambda_share_L1"),
                "lambda_share_L2": row.get("lambda_share_L2")}
    q["Q5"] = q5

    all_verts = [c.get("verdict", "PASS") for c in summary["cells"].values()]
    n_fail = sum(1 for v in all_verts if v == "FAIL")
    n_concern = sum(1 for v in all_verts if v == "CONCERN")
    q["Q6"] = {"n_FAIL": n_fail, "n_CONCERN": n_concern,
               "n_cells": len(all_verts),
               "cells": {k: c.get("verdict")
                         for k, c in summary["cells"].items()}}
    summary["q"] = q

    with open(f"{args.outdir}/d6_summary.json", "w") as f:
        json.dump(summary, f, indent=2, default=str)
    with open(f"{args.outdir}/d6_pairwise_attribution.tsv", "w") as f:
        f.write("REGIME\ttier\tcore\tpair\tn_snp\tpearson\tslope"
                "\trmse\tmean_abs_diff\n")
        for r in pairwise_rows:
            f.write(f"{r['regime']}\t{r['tier']}\t{r['core']}\t{r['pair']}"
                    f"\t{r['n_snp']}\t{r['pearson']:.6f}\t{r['slope']:.6f}"
                    f"\t{r['rmse']:.3e}\t{r['mean_abs_diff']:.3e}\n")

    print("\n================ D6 (per-regime) summary ================")
    print(f"REGIME={regime}  reps={reps}")
    for k, c in summary["cells"].items():
        print(f"  {k:<36} lambda={c.get('lambda_pooled', float('nan')):.4f}"
              f" FPR05={c.get('fpr05', float('nan')):.5f} "
              f"-> {c.get('verdict')}")
    print("Q1 (R3 null calibration @K98/full):")
